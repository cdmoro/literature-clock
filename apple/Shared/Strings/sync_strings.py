#!/usr/bin/env python3
"""Generate macOS app and widget Localizable.strings from source catalogues."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
STRING_DIR = ROOT / "src/strings"
DESTINATION = ROOT / "apple/Shared/Strings"


def load_catalogue(path: Path) -> dict[str, dict[str, str]]:
    return json.loads(path.read_text(encoding="utf-8"))


def quote(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main() -> int:
    sources = [
        load_catalogue(STRING_DIR / "common/translations.json"),
        load_catalogue(STRING_DIR / "web/settings.json"),
        load_catalogue(STRING_DIR / "common/settings.json"),
        load_catalogue(STRING_DIR / "macos-app/interface.json"),
    ]
    web_reading = load_catalogue(STRING_DIR / "web/reading.json")
    fallback_quotes = json.loads((STRING_DIR / "common/fallbackQuotes.json").read_text(encoding="utf-8"))
    locales = set(sources[0])
    if any(set(source) != locales for source in sources[1:]) or set(web_reading) != locales or set(fallback_quotes) != locales:
        raise SystemExit("All macOS app string catalogues must cover the same locales")

    for locale in sorted(locales):
        merged: dict[str, str] = {}
        for source in sources:
            merged.update(source[locale])
        for key in ("pause", "resume", "pausedAt"):
            merged[key] = web_reading[locale][key]
        fallback = next(quote for quote in fallback_quotes[locale] if quote.get("id") == "F-001")
        for key, field in (("app_fallback_error_prefix", "quote_first"), ("app_fallback_error_suffix", "quote_last"),
                           ("app_fallback_error_title", "title"), ("app_fallback_error_author", "author")):
            merged[key] = fallback[field]
        destination = DESTINATION / f"{locale}.lproj/Localizable.strings"
        destination.parent.mkdir(parents=True, exist_ok=True)
        rows = ["/* Generated by sync_strings.py. Edit src/strings catalogs instead. */"]
        rows.extend(f"{quote(key)} = {quote(value)};" for key, value in sorted(merged.items()))
        destination.write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"Generated native strings for {len(locales)} locales")
    return 0


if __name__ == "__main__":
    sys.exit(main())
